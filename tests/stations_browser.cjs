/* Real browser + isolated SIM server. Start with python -m tests.stations_browser. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const browser = await chromium.launch({channel:'msedge',headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  const page = await context.newPage();
  const errors=[],checks=[];
  const check = message => { checks.push(message); console.log(message); };
  let token;
  page.on('request',r=>{if(r.url().includes('/api/events?'))token=new URL(r.url()).searchParams.get('token');});
  page.on('pageerror',e=>errors.push(e.message));
  const post = (url,data) => page.evaluate(async({url,data,token})=>{
    const r=await fetch(url,{method:'POST',headers:{'Content-Type':'application/json','X-Session':token},body:JSON.stringify(data)});
    const result=await r.json(); if(!result.ok)throw Error(JSON.stringify(result));return result;
  },{url,data,token});
  const snapshot = ()=>page.evaluate(async()=>(await fetch('/api/state')).json());
  const until = async predicate => { const deadline=Date.now()+90000; while(Date.now()<deadline){if(await predicate())return;await new Promise(r=>setTimeout(r,100));}const s=await snapshot();throw Error('state timeout: '+JSON.stringify({task:s.task,nav:s.navigation,log:s.log?.slice(-5)}));};
  const waitState = state=>until(async()=>(await snapshot()).task.state===state);
  try {
    await page.goto(new URL('/debug', process.env.NAV_URL).href);
    await page.getByRole('tab',{name:'坐标巡航'}).click();
    await page.waitForFunction(()=>!document.getElementById('nav-origin').disabled);
    assert.equal((await snapshot()).demo,true);
    const order=[1,2,3,4,2,3,4,1,0];
    const nav={stations:[{name:'O',x:0,y:0,heading:0},{name:'A',x:0,y:14,heading:0},
      {name:'B',x:14,y:0,heading:0},{name:'C',x:14,y:28,heading:0},{name:'D',x:28,y:14,heading:0}],
      route:order.map(station=>({station,hold:1})),grid:{x:[0,14,28],y:[0,14,28]},sps:500,accel:2000,dwell_ms:0};
    await post('/api/navigation/config',{config:nav});
    await page.waitForFunction(()=>document.querySelectorAll('#nav-route tbody tr').length===9);
    assert.equal(await page.locator('#nav-route-tag').textContent(),'O → A → B → C → D → B → C → D → A → O');
    check('nine-leg repeated station route and hold flags');
    const y=page.locator('[data-station="1"] input').nth(2);
    await y.fill('15');
    await page.locator('[data-station="2"] input').nth(0).fill('');
    for(const id of ['nav-leg-add','nav-station-add','nav-leg-remove','nav-station-remove'])await page.locator('#'+id).click();
    assert.equal(await y.inputValue(),'15');
    assert.equal(await page.locator('[data-station="2"] input').nth(0).inputValue(),'');
    assert.equal(await page.locator('#nav-route tbody tr').count(),9);
    assert.equal(await page.locator('#nav-points tbody tr').count(),5);
    await page.locator('[data-station="2"] input').nth(0).fill('B');
    await page.locator('#nav-leg-add').click();
    assert.equal(await y.inputValue(),'15');
    assert.equal(await page.locator('#nav-route tbody tr').count(),10);
    check('valid and invalid unsaved drafts preserved during structural editing');
    await post('/api/navigation/config',{config:nav});
    await page.waitForFunction(()=>document.querySelectorAll('#nav-route tbody tr').length===9);
    const observer=await context.newPage();
    observer.on('pageerror',e=>errors.push(e.message));
    await observer.goto(new URL('/debug', process.env.NAV_URL).href);
    await observer.getByRole('tab',{name:'坐标巡航'}).click();
    await observer.waitForFunction(()=>document.querySelector('#nav-route select')?.disabled);
    for(const id of ['nav-leg-add','nav-station-add','task-start','task-save'])assert.equal(await observer.locator('#'+id).isDisabled(),true);
    check('readonly page cannot edit route structure or start tasks');
    await observer.close();
    const task=(await snapshot()).task_config;
    task.legs=Object.fromEntries(order.map((_,i)=>[String(i+1),[]]));
    task.legs['1']=[{op:'scan',key:'task'}];
    await page.locator('#task-panel summary').click();
    await page.locator('#task-config').fill(JSON.stringify(task,null,2));
    await page.locator('#task-save').click();
    await until(async()=>(await snapshot()).task_config.legs['1']?.[0]?.op==='scan');
    await page.locator('#nav-origin').click();
    await page.waitForFunction(()=>document.getElementById('nav-position').textContent==='(0, 0)');
    await page.locator('#btn-arm').click();
    await page.waitForFunction(()=>!document.getElementById('task-start').disabled);
    await page.locator('#task-start').click();
    await waitState('vision');
    await page.waitForFunction(()=>document.getElementById('task-state').textContent==='等待视觉');
    for(const id of ['nav-leg-add','nav-start','task-save','task-start'])assert.equal(await page.locator('#'+id).isDisabled(),true,id);
    assert.equal(await page.locator('#btn-stop').isEnabled(),true);
    assert.equal(await page.locator('#task-stop').isEnabled(),true);
    const refused=await page.evaluate(async token=>(await (await fetch('/api/jog',{method:'POST',headers:{'Content-Type':'application/json','X-Session':token},body:JSON.stringify({body:'CHASSIS JOG FWD 100 1000'})})).json()),token);
    assert.equal(refused.ok,false);
    check('task request shown, manual control locked, global/task STOP available');
    const request=(await snapshot()).task.request;
    const sample={...request,source:'browser-test',frame_id:1,captured_at:Date.now()/1000,found:true,text:'123+321+456+654'};
    await post('/api/mission/vision',{sample});
    await waitState('done');
    const completed=await snapshot();
    assert.equal(completed.task.scans.task,'123+321+456+654');
    check('HTTP vision result resumes and finishes all nine held legs');
    await page.locator('#btn-stop').click();
    await page.waitForFunction(()=>document.getElementById('m-armed').textContent==='已关闭');
    await page.reload();await page.getByRole('tab',{name:'坐标巡航'}).click();
    await page.waitForFunction(()=>document.getElementById('task-config').value.includes('scan'));
    await page.locator('#nav-origin').click();
    await page.waitForFunction(()=>!document.getElementById('btn-arm').disabled);
    await page.locator('#btn-arm').click();
    await page.waitForFunction(()=>!document.getElementById('task-start').disabled);
    await page.locator('#task-start').click();await waitState('vision');
    await page.locator('#task-stop').click();await waitState('stopped');
    await until(async()=>(await snapshot()).armed===false);
    await until(async()=>!['waiting','turning','moving','orienting','nudging'].includes((await snapshot()).navigation.state));
    check('reload preserves plan; STOP cancels vision wait and disarms');
    nav.route.forEach(leg=>leg.hold=0);
    await post('/api/navigation/config',{config:nav});
    await page.waitForFunction(()=>[...document.querySelectorAll('#nav-route input[type=checkbox]')].every(e=>!e.checked));
    await post('/api/navigation/action',{action:'origin'});
    await until(async()=>(await snapshot()).navigation.ready==='1');
    await post('/api/command',{body:'ARM 1'});
    await page.waitForFunction(()=>!document.getElementById('nav-start').disabled);
    await page.locator('#nav-start').click();
    await until(async()=>(await snapshot()).navigation.state==='done');
    await post('/api/command',{body:'STOP'});
    check('ordinary navigation still finishes without task orchestration');
    fs.mkdirSync(path.join(__dirname,'../tmp'),{recursive:true});
    for(const width of [1440,760,390]){
      await page.setViewportSize({width,height:1000});
      await page.screenshot({path:path.join(__dirname,`../tmp/mission_${width}.png`),fullPage:true});
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`overflow ${width}`);
    }
    check('desktop and 760/390px layouts fit viewport');
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({ok:true,checks,pageErrors:errors},null,2));
    fs.writeFileSync(path.join(__dirname,'../tmp/mission_browser_validation.json'),JSON.stringify({ok:true,checks,pageErrors:errors},null,2));
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
